-- لعملية إدخال الخامة، وأصبح غير مطلوب: البيع الآن يُحدَّد من واجهة إضافة
-- الأتواب نفسها (أتواب مُحدَّدة للبيع ضمن إجراء "مخزون")، وليس من سجل مُعدّ
